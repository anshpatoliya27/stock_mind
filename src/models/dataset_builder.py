"""Dataset Builder and Feature Engineering Pipeline for StockMind AI.

Implements leak-proof dataset preparation for supervised stock return forecasting:
- Target 1: Next-trading-day return: (Close_{t+1} / Close_t - 1) * 100
- Target 2: Five-trading-day return: (Close_{t+5} / Close_t - 1) * 100
- Strict chronological sorting by [symbol, date]
- Backward-looking feature calculation (strictly <= t)
- Preprocessing (scalers, imputers) fitted strictly on training data only
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union

import numpy as np
import pandas as pd
from sklearn.base import BaseEstimator, TransformerMixin
from sklearn.preprocessing import RobustScaler

logger = logging.getLogger("stockmind.dataset_builder")

# Standard list of technical feature names generated by the pipeline
FEATURE_NAMES: List[str] = [
    # Backward Price Returns (%)
    "ret_1d",
    "ret_2d",
    "ret_5d",
    "ret_10d",
    "ret_20d",
    "open_to_close_ret",
    # Moving Average Ratios (Close / EMA - 1.0)
    "ema_ratio_9",
    "ema_ratio_21",
    "ema_ratio_50",
    "ema_ratio_200",
    "trend_ema_50_200",
    # Momentum Oscillators
    "rsi_14",
    "macd_line_pct",
    "macd_signal_pct",
    "macd_hist_pct",
    # Volatility & Dispersion
    "volatility_20d",
    "natr_14",
    # Volume Dynamics
    "volume_ratio_5_20",
    "log_volume",
    # Price Range Position (0.0 to 1.0)
    "range_pos_20d",
    "range_pos_52w",
]


@dataclass
class SplitConfig:
    """Chronological split boundaries for anti-lookahead evaluation."""
    train_start: str = "2019-01-01"
    train_end: str = "2023-12-31"
    val_start: str = "2024-01-01"
    val_end: str = "2024-12-31"
    test_start: str = "2025-01-01"
    test_end: str = "2026-12-31"


class PreprocessingPipeline(BaseEstimator, TransformerMixin):
    """Leakage-free preprocessor that imputes and scales features using train-set statistics only."""

    def __init__(self, feature_names: Optional[List[str]] = None):
        self.feature_names = feature_names or FEATURE_NAMES
        self.medians_: Dict[str, float] = {}
        self.scaler_: Optional[RobustScaler] = None
        self.is_fitted_: bool = False

    def fit(self, X: pd.DataFrame, y: Optional[Any] = None) -> PreprocessingPipeline:
        """Fit median values and RobustScaler strictly on training data."""
        if not isinstance(X, pd.DataFrame):
            X = pd.DataFrame(X, columns=self.feature_names)

        # 1. Learn median imputation values from training data only
        self.medians_ = {}
        X_imputed = X.copy()
        for col in self.feature_names:
            if col in X_imputed.columns:
                med = float(X_imputed[col].median(skipna=True))
                med_val = 0.0 if np.isnan(med) else med
                self.medians_[col] = med_val
                X_imputed[col] = X_imputed[col].fillna(med_val)
            else:
                self.medians_[col] = 0.0

        # 2. Fit RobustScaler (resistant to outliers in financial returns)
        self.scaler_ = RobustScaler()
        self.scaler_.fit(X_imputed[self.feature_names])
        self.is_fitted_ = True
        return self

    def transform(self, X: pd.DataFrame) -> np.ndarray:
        """Impute and scale out-of-sample data using train-set learned parameters."""
        if not self.is_fitted_ or self.scaler_ is None:
            raise RuntimeError("PreprocessingPipeline must be fitted on training data before transform.")

        if not isinstance(X, pd.DataFrame):
            X = pd.DataFrame(X, columns=self.feature_names)

        X_imputed = X.copy()
        for col in self.feature_names:
            med_val = self.medians_.get(col, 0.0)
            if col in X_imputed.columns:
                X_imputed[col] = X_imputed[col].fillna(med_val)
            else:
                X_imputed[col] = med_val

        return self.scaler_.transform(X_imputed[self.feature_names])


class DatasetBuilder:
    """Prepares clean, chronological, zero-lookahead feature matrices from raw daily market data."""

    @staticmethod
    def load_parquet_dataset(
        data_dir: Path | str,
        series_filter: str = "EQ",
        symbols_filter: Optional[List[str]] = None,
        min_date: Optional[str] = None,
        max_date: Optional[str] = None,
    ) -> Tuple[pd.DataFrame, Dict[str, Any]]:
        """Load and filter NSE daily Parquet files with semantic integrity checks.
        
        Returns:
            Tuple of (clean_df, metadata_report_dict)
        """
        data_path = Path(data_dir)
        parquet_files = sorted(list(data_path.glob("*.parquet")))
        if not parquet_files:
            raise FileNotFoundError(f"No parquet files found in directory: {data_dir}")

        columns_to_load = [
            "date", "symbol", "series", "open", "high", "low", "close", "prev_close", "volume"
        ]

        chunks: List[pd.DataFrame] = []
        total_raw_rows = 0
        excluded_series_rows = 0
        excluded_symbol_rows = 0

        for f in parquet_files:
            df_chunk = pd.read_parquet(f, columns=columns_to_load)
            total_raw_rows += len(df_chunk)

            # 1. Filter series (default 'EQ' standard equity shares)
            if series_filter:
                mask_series = df_chunk["series"] == series_filter
                excluded_series_rows += int((~mask_series).sum())
                df_chunk = df_chunk[mask_series]

            # 2. Optional symbol whitelist (e.g. NIFTY 50 universe)
            if symbols_filter:
                sym_set = set(s.upper() for s in symbols_filter)
                mask_sym = df_chunk["symbol"].str.upper().isin(sym_set)
                excluded_symbol_rows += int((~mask_sym).sum())
                df_chunk = df_chunk[mask_sym]

            # 3. Date bounds filtering
            if min_date:
                df_chunk = df_chunk[df_chunk["date"] >= pd.to_datetime(min_date).date()]
            if max_date:
                df_chunk = df_chunk[df_chunk["date"] <= pd.to_datetime(max_date).date()]

            chunks.append(df_chunk)

        if not chunks or all(c.empty for c in chunks):
            raise ValueError(f"No data matching filters found in {data_dir}")

        full_df = pd.concat(chunks, ignore_index=True)

        # Ensure consistent typing
        full_df["date"] = pd.to_datetime(full_df["date"])
        for col in ["open", "high", "low", "close", "prev_close"]:
            full_df[col] = full_df[col].astype(np.float64)
        full_df["volume"] = full_df["volume"].astype(np.float64)

        # Semantic Deduplication & Sorting:
        # Mandatory: Sort strictly by symbol and date first!
        initial_len = len(full_df)
        full_df = full_df.drop_duplicates(subset=["symbol", "date"]).sort_values(
            by=["symbol", "date"]
        ).reset_index(drop=True)
        dedup_dropped = initial_len - len(full_df)

        report = {
            "total_raw_rows_scanned": total_raw_rows,
            "retained_rows": len(full_df),
            "excluded_non_eq_rows": excluded_series_rows,
            "excluded_symbol_rows": excluded_symbol_rows,
            "duplicates_dropped": dedup_dropped,
            "unique_symbols": int(full_df["symbol"].nunique()),
            "start_date": str(full_df["date"].min().date()),
            "end_date": str(full_df["date"].max().date()),
        }
        return full_df, report

    @classmethod
    def compute_symbol_features(cls, df: pd.DataFrame) -> pd.DataFrame:
        """Compute backward-looking technical features strictly grouped by symbol.
        
        Guarantees:
        - Symbols never share rolling history (grouped by symbol).
        - Every feature at time t uses data strictly <= t.
        - No forward information is accessed.
        """
        # Ensure chronological order per symbol
        df = df.sort_values(by=["symbol", "date"]).copy()

        def _calc_group_features(g: pd.DataFrame) -> pd.DataFrame:
            close = g["close"]
            open_ = g["open"]
            high = g["high"]
            low = g["low"]
            volume = g["volume"]

            # Backward Returns (%)
            g["ret_1d"] = (close / close.shift(1) - 1.0) * 100.0
            g["ret_2d"] = (close / close.shift(2) - 1.0) * 100.0
            g["ret_5d"] = (close / close.shift(5) - 1.0) * 100.0
            g["ret_10d"] = (close / close.shift(10) - 1.0) * 100.0
            g["ret_20d"] = (close / close.shift(20) - 1.0) * 100.0
            g["open_to_close_ret"] = (close / open_ - 1.0) * 100.0

            # Exponential Moving Averages (adjust=False ensures strict iterative formula)
            ema_9 = close.ewm(span=9, adjust=False).mean()
            ema_21 = close.ewm(span=21, adjust=False).mean()
            ema_50 = close.ewm(span=50, adjust=False).mean()
            ema_200 = close.ewm(span=200, adjust=False).mean()

            g["ema_ratio_9"] = (close / ema_9 - 1.0) * 100.0
            g["ema_ratio_21"] = (close / ema_21 - 1.0) * 100.0
            g["ema_ratio_50"] = (close / ema_50 - 1.0) * 100.0
            g["ema_ratio_200"] = (close / ema_200 - 1.0) * 100.0
            g["trend_ema_50_200"] = (ema_50 / ema_200 - 1.0) * 100.0

            # Relative Strength Index (RSI 14)
            delta = close.diff()
            gain = delta.clip(lower=0)
            loss = (-delta).clip(lower=0)
            avg_gain = gain.rolling(window=14, min_periods=14).mean()
            avg_loss = loss.rolling(window=14, min_periods=14).mean()
            rs = avg_gain / (avg_loss.replace(0, np.nan))
            g["rsi_14"] = 100.0 - (100.0 / (1.0 + rs))

            # MACD (12, 26, 9)
            fast_ema = close.ewm(span=12, adjust=False).mean()
            slow_ema = close.ewm(span=26, adjust=False).mean()
            macd_line = fast_ema - slow_ema
            macd_sig = macd_line.ewm(span=9, adjust=False).mean()
            macd_hist = macd_line - macd_sig
            g["macd_line_pct"] = (macd_line / close) * 100.0
            g["macd_signal_pct"] = (macd_sig / close) * 100.0
            g["macd_hist_pct"] = (macd_hist / close) * 100.0

            # Volatility (20-day annualized realized volatility)
            log_ret = np.log(close / close.shift(1))
            g["volatility_20d"] = log_ret.rolling(window=20, min_periods=10).std() * np.sqrt(252) * 100.0

            # Normalized ATR 14
            prev_close = close.shift(1)
            tr1 = high - low
            tr2 = (high - prev_close).abs()
            tr3 = (low - prev_close).abs()
            tr = pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
            atr_14 = tr.rolling(window=14, min_periods=14).mean()
            g["natr_14"] = (atr_14 / close) * 100.0

            # Volume Dynamics
            vol_5 = volume.rolling(window=5, min_periods=3).mean()
            vol_20 = volume.rolling(window=20, min_periods=10).mean()
            g["volume_ratio_5_20"] = vol_5 / (vol_20.replace(0, np.nan))
            g["log_volume"] = np.log1p(volume)

            # Price Range Position (0.0 = at low, 1.0 = at high)
            high_20 = high.rolling(window=20, min_periods=10).max()
            low_20 = low.rolling(window=20, min_periods=10).min()
            denom_20 = high_20 - low_20
            g["range_pos_20d"] = ((close - low_20) / denom_20.replace(0, np.nan)).clip(0.0, 1.0)

            high_52w = high.rolling(window=252, min_periods=40).max()
            low_52w = low.rolling(window=252, min_periods=40).min()
            denom_52w = high_52w - low_52w
            g["range_pos_52w"] = ((close - low_52w) / denom_52w.replace(0, np.nan)).clip(0.0, 1.0)

            return g

        chunks: List[pd.DataFrame] = []
        for _, group in df.groupby("symbol", sort=False):
            chunks.append(_calc_group_features(group.copy()))

        features_df = pd.concat(chunks, ignore_index=True)
        return features_df

    @classmethod
    def construct_targets(cls, df: pd.DataFrame) -> pd.DataFrame:
        """Construct exact future return targets strictly grouped by symbol.
        
        MANDATORY FORMULAS:
        - target_1d = (grouped_close.shift(-1) / close - 1) * 100
        - target_5d = (grouped_close.shift(-5) / close - 1) * 100
        
        Note on Data Semantics:
        A 5-row shift means 5 available valid trading observations for that symbol,
        not necessarily 5 calendar days (accounting for weekends and market holidays).
        """
        df = df.sort_values(by=["symbol", "date"]).copy()
        grouped_close = df.groupby("symbol")["close"]
        df["target_1d"] = (grouped_close.shift(-1) / df["close"] - 1.0) * 100.0
        df["target_5d"] = (grouped_close.shift(-5) / df["close"] - 1.0) * 100.0
        return df

    @classmethod
    def split_chronological(
        cls,
        df: pd.DataFrame,
        config: SplitConfig,
    ) -> Dict[str, pd.DataFrame]:
        """Split dataframe into Train, Validation, and Test sets based strictly on date boundaries.
        
        Guarantees:
        - No future data exists in Train.
        - Validation and Test dates are never mixed.
        """
        train_mask = (df["date"] >= pd.to_datetime(config.train_start)) & (
            df["date"] <= pd.to_datetime(config.train_end)
        )
        val_mask = (df["date"] >= pd.to_datetime(config.val_start)) & (
            df["date"] <= pd.to_datetime(config.val_end)
        )
        test_mask = (df["date"] >= pd.to_datetime(config.test_start)) & (
            df["date"] <= pd.to_datetime(config.test_end)
        )

        splits = {
            "train": df[train_mask].copy().reset_index(drop=True),
            "val": df[val_mask].copy().reset_index(drop=True),
            "test": df[test_mask].copy().reset_index(drop=True),
        }
        return splits
